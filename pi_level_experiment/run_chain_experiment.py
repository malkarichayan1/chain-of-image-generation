@torch.no_grad()
def person_boxes(models: Models, image: Image.Image, max_people: int, score_thresh: float = 0.7) -> List[List[float]]:
    t = TF.to_tensor(image).to(DEVICE)
    out = models.detector([t])[0]
    keep = (out["labels"] == COCO_PERSON) & (out["scores"] >= score_thresh)
    boxes, scores = out["boxes"][keep], out["scores"][keep]
    if boxes.shape[0] == 0:
        return []
    order = scores.argsort(descending=True)[:max_people]
    return boxes[order].cpu().numpy().tolist()


@torch.no_grad()
def assign_subjects(models: Models, image: Image.Image, boxes: List[List[float]],
                     subject_names: List[str]) -> Dict[str, int]:
    from scipy.optimize import linear_sum_assignment

    crops = [image.crop(tuple(b)) for b in boxes]
    inp = models.clip_proc(text=[f"a photo of a {s}" for s in subject_names],
                            images=crops, return_tensors="pt", padding=True).to(DEVICE)
    sim = models.clip_model(**inp).logits_per_image.softmax(-1).cpu().numpy()
    r, c = linear_sum_assignment(-sim)
    return {subject_names[j]: int(i) for i, j in zip(r, c)}


def box_mask(image: Image.Image, box: List[float], pad_frac: float = 0.15) -> Image.Image:
    """White = editable region for inpainting. Padded box around the subject so the
    inpaint has enough context to blend the new attribute in, still leaving everything
    outside the box (including earlier-added attributes on other subjects) untouched."""
    w, h = image.size
    x0, y0, x1, y1 = box
    bw, bh = x1 - x0, y1 - y0
    x0 = max(0, x0 - bw * pad_frac)
    y0 = max(0, y0 - bh * pad_frac)
    x1 = min(w, x1 + bw * pad_frac)
    y1 = min(h, y1 + bh * pad_frac)
    mask = Image.new("L", (w, h), 0)
    draw = ImageDraw.Draw(mask)
    draw.rectangle([x0, y0, x1, y1], fill=255)
    return mask


def token_indices(tokenizer, prompt: str, phrase: str) -> List[int]:
    """Positions of `phrase` within the padded 77-token CLIP sequence. Copied from
    metric A's notebook -- handles multi-word phrases like 'red apron' by matching the
    phrase's own encoded sub-sequence against the full prompt's tokens, rather than
    Pranav's single-token find_token_index (which only matches one exact token)."""
    ids = tokenizer(prompt, padding="max_length", max_length=77, truncation=True).input_ids
    target = tokenizer(phrase, add_special_tokens=False).input_ids
    if not target:
        raise ValueError(f"phrase {phrase!r} tokenized to nothing")
    for i in range(len(ids) - len(target) + 1):
        if ids[i:i + len(target)] == target:
            return list(range(i, i + len(target)))
    raise ValueError(f"phrase {phrase!r} not found in prompt tokens: {prompt!r}")


def multi_token_attention_map(metric: SpatialSemanticAlignment, tokenizer, prompt: str, phrase: str) -> np.ndarray:
    """Average phase_b_cross_attention_map over every token in a multi-word phrase.
    cond_index=1 matches build_chain's guidance_scale=7.5 calls, which run classifier-
    free guidance with batch order [uncond, cond] -- selecting the conditional half only,
    the same convention metric A's own AttentionStore uses."""
    idxs = token_indices(tokenizer, prompt, phrase)
    maps = [metric.phase_b_cross_attention_map(target_token_index=i, cond_index=1) for i in idxs]
    return np.mean(maps, axis=0)


@torch.no_grad()
def encode_to_latents(pipe, image: Image.Image) -> torch.Tensor:
    img_t = TF.to_tensor(image).unsqueeze(0).to(device=DEVICE, dtype=DTYPE)
    img_t = img_t * 2.0 - 1.0  # [0,1] -> [-1,1], matches VAE's expected input range
    latents = pipe.vae.encode(img_t).latent_dist.sample()
    return latents * pipe.vae.config.scaling_factor


def mask_to_latent_tensor(mask_image: Image.Image, latent_hw: Tuple[int, int]) -> torch.Tensor:
    """1.0 = editable (generated) region, 0.0 = keep-original region, at latent resolution.
    latent_hw is (height, width) in latent space; PIL .resize wants (width, height)."""
    lh, lw = latent_hw
    small = mask_image.resize((lw, lh), Image.NEAREST)
    arr = (np.array(small).astype(np.float32) / 255.0 > 0.5).astype(np.float32)
    t = torch.from_numpy(arr).to(device=DEVICE, dtype=DTYPE)
    return t.unsqueeze(0).unsqueeze(0)  # (1,1,h,w) -- broadcasts over the 4 latent channels


# =============================================================================
# Chain construction
# =============================================================================

@dataclass
class ChainStep:
    attribute: str
    subject: str
    image: Image.Image
    attention_map: np.ndarray  # captured at this step's introduction, early window


@dataclass
class Chain:
    chain_id: int
    spec: dict
    images: List[Image.Image]         # images[0] = base, images[i] = after step i
    steps: List[ChainStep]             # one per attribute, in introduction order
    subject_boxes: Dict[str, List[float]]


def build_chain(chain_id: int, spec: dict, metric: SpatialSemanticAlignment, models: Models) -> Optional[Chain]:
    base_prompt = base_prompt_for(spec)
    subjects = [s for s, _, _ in spec["pairs"]]

    # txt2img is unhooked for this call (attn processor is only swapped in for the
    # attribute steps below), so no attention is captured or needed for the base image.
    g = torch.Generator(DEVICE).manual_seed(SEED)
    base_image = models.txt2img(base_prompt, num_inference_steps=NUM_INFERENCE_STEPS,
                                 guidance_scale=7.5, generator=g).images[0]

    boxes = person_boxes(models, base_image, max_people=spec["n"])
    if len(boxes) != spec["n"]:
        print(f"  chain {chain_id}: SKIP -- detected {len(boxes)} people, expected {spec['n']}")
        return None
    assign = assign_subjects(models, base_image, boxes, subjects)
    subject_boxes = {s: boxes[assign[s]] for s in subjects}

    images = [base_image]
    steps: List[ChainStep] = []
    current = base_image

    for subject, attribute, _region in spec["pairs"]:
        mask_img = box_mask(current, subject_boxes[subject])
        inpaint_prompt = f"a {subject} with a {attribute}"

        # RePaint-style lock: generate a full image from scratch, but at every
        # denoising step force the region outside the subject's mask to match the
        # correctly-noised original image at that step's noise level. By the final
        # step (noise level 0) that region equals the original pixels exactly, so
        # only the masked region is actually new -- everything else, including
        # attributes added at earlier steps, is frozen by construction.
        orig_latents = encode_to_latents(models.txt2img, current)
        lh, lw = orig_latents.shape[-2], orig_latents.shape[-1]
        mask_latent = mask_to_latent_tensor(mask_img, (lh, lw))
        blend_noise = torch.randn(orig_latents.shape, generator=torch.Generator(DEVICE).manual_seed(SEED),
                                   device=DEVICE, dtype=DTYPE)

        metric.hook_pipeline(models.txt2img)

        def _cb(pipe, i, t, kw):
            metric.attn_store.step()
            latents = kw["latents"]
            timesteps = pipe.scheduler.timesteps
            if i + 1 < len(timesteps):
                next_t = timesteps[i + 1].unsqueeze(0)
                noised_orig = pipe.scheduler.add_noise(orig_latents, blend_noise, next_t)
            else:
                noised_orig = orig_latents  # last step -> exact original outside the mask
            kw["latents"] = mask_latent * latents + (1.0 - mask_latent) * noised_orig
            return kw

        g = torch.Generator(DEVICE).manual_seed(SEED)
        edited = models.txt2img(
            prompt=inpaint_prompt, num_inference_steps=NUM_INFERENCE_STEPS, guidance_scale=7.5,
            generator=g, callback_on_step_end=_cb,
        ).images[0]

        attn_map = multi_token_attention_map(metric, models.txt2img.tokenizer, inpaint_prompt, attribute)
        metric.unhook_pipeline(models.txt2img)

        steps.append(ChainStep(attribute=attribute, subject=subject, image=edited, attention_map=attn_map))
        images.append(edited)
        current = edited

    return Chain(chain_id=chain_id, spec=spec, images=images, steps=steps, subject_boxes=subject_boxes)


# =============================================================================
# Scoring: REAL / SHUFFLED / SUBSTITUTED / ATTENTION-SCRAMBLED
# =============================================================================

def score_chains(chains: List[Chain], metric: SpatialSemanticAlignment) -> pd.DataFrame:
    rows = []

    for c in chains:
        k = len(c.steps)
        for i, step in enumerate(c.steps):
            true_step_idx = i + 1  # images[0] is the base; step i's output is images[i+1]

            # ---- REAL: correct attribute, correct step ----
            delta_real = metric.phase_a_delta_mask(
                c.images[true_step_idx], c.images[true_step_idx - 1], step.attribute
            )
            iou_real = metric.phase_c_alignment_score(step.attention_map, delta_real)
            rows.append(dict(condition="real", chain_id=c.chain_id, n=c.spec["n"],
                              attribute=step.attribute, subject=step.subject,
                              claimed_step=true_step_idx, true_step=true_step_idx, iou=iou_real))

            # ---- SHUFFLED: correct attribute, wrong step within the same chain ----
            other_steps = [s for s in range(1, k + 1) if s != true_step_idx]
            for wrong_step in other_steps:
                delta_shuf = metric.phase_a_delta_mask(
                    c.images[wrong_step], c.images[wrong_step - 1], step.attribute
                )
                iou_shuf = metric.phase_c_alignment_score(step.attention_map, delta_shuf)
                rows.append(dict(condition="shuffled", chain_id=c.chain_id, n=c.spec["n"],
                                  attribute=step.attribute, subject=step.subject,
                                  claimed_step=wrong_step, true_step=true_step_idx, iou=iou_shuf))

            # ---- SUBSTITUTED: a foreign attribute from a different chain, never in this one ----
            foreign_chain = random.choice([fc for fc in chains if fc.chain_id != c.chain_id])
            foreign_step = random.choice(foreign_chain.steps)
            delta_sub = metric.phase_a_delta_mask(
                c.images[true_step_idx], c.images[true_step_idx - 1], foreign_step.attribute
            )
            iou_sub = metric.phase_c_alignment_score(step.attention_map, delta_sub)
            rows.append(dict(condition="substituted", chain_id=c.chain_id, n=c.spec["n"],
                              attribute=f"{foreign_step.attribute} (from chain {foreign_chain.chain_id})",
                              subject=step.subject, claimed_step=true_step_idx,
                              true_step=true_step_idx, iou=iou_sub))

            # ---- ATTENTION-SCRAMBLED: correct delta target, wrong attention map ----
            # metric A's Tier-1 falsification test #1, ported to the chain setting: if
            # Phase C's score depended only on delta-mask size (not attention content),
            # this would match REAL. A real drop shows attention content is load-bearing.
            other_attr_steps = [s for s in c.steps if s.attribute != step.attribute]
            if other_attr_steps:
                wrong_attn_step = random.choice(other_attr_steps)
                iou_scrambled = metric.phase_c_alignment_score(wrong_attn_step.attention_map, delta_real)
                rows.append(dict(condition="attention_scrambled", chain_id=c.chain_id, n=c.spec["n"],
                                  attribute=step.attribute, subject=step.subject,
                                  claimed_step=true_step_idx, true_step=true_step_idx, iou=iou_scrambled))

    return pd.DataFrame(rows)


# =============================================================================
# Main
# =============================================================================

def main():
    random.seed(SEED)
    metric = SpatialSemanticAlignment(device=DEVICE, lazy_load_model=True)
    print("\nLoading models (SD1.5 txt2img + inpaint, Mask R-CNN, CLIP)...")
    models = load_all_models()

    chains: List[Chain] = []
    t0 = time.time()
    for i, spec in enumerate(MECHANISM_PROMPTS):
        print(f"\n=== building chain {i}: {spec['prompt'][:70]}... ===")
        try:
            chain = build_chain(i, spec, metric, models)
            if chain is not None:
                chains.append(chain)
                print(f"  chain {i}: OK, {len(chain.steps)} attribute steps")
        except Exception as e:
            print(f"  chain {i}: ERROR {type(e).__name__}: {e}")
            traceback.print_exc()
    print(f"\nBuilt {len(chains)}/{len(MECHANISM_PROMPTS)} chains in {time.time() - t0:.1f}s")

    if not chains:
        print("No chains built successfully -- aborting scoring.")
        return

    df = score_chains(chains, metric)
    df.to_csv("chain_experiment_results.csv", index=False)

    print("\n=== Summary by condition ===")
    summary = df.groupby("condition")["iou"].agg(["mean", "std", "median", "count"])
    print(summary.round(4))

    real_mean = summary.loc["real", "mean"] if "real" in summary.index else float("nan")
    print("\n=== Money-result check ===")
    for cond in ("shuffled", "substituted", "attention_scrambled"):
        if cond in summary.index:
            gap = real_mean - summary.loc[cond, "mean"]
            print(f"real ({real_mean:.4f}) - {cond} ({summary.loc[cond, 'mean']:.4f}) = {gap:.4f}")

    df.to_json("chain_experiment_results.json", orient="records", indent=2)
    print("\nSaved chain_experiment_results.csv / .json")


if __name__ == "__main__":
    main()
