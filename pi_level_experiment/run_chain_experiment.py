#!/usr/bin/env python
"""
Combined SSA chain experiment — the "money result" for the PI-level combined arc.

Track 1 (Causal Relevance pilot, docs/pilot-design.md + pilot/) found that CoIG's own
compositional lock makes a *persistence*-based faithfulness check blind: real chains and
shuffled (wrong-step) chains both showed persists_to_final = 0.83. Track 2 built two
separate metrics to fix this:

  Metric A (ssa/coig_ssa_colab.ipynb) -- validated that SD1.5's cross-attention tracks
  correct attribute-to-subject binding in one-shot generation (OWL-ViT ground truth).

  Metric B (pilot/spatial_semantic_alignment.py, this project's Pranav) -- a Delta-Mask +
  attention-IoU design that is immune to the lock confound *by construction*: if an
  attribute was already locked in before the step being scored, Delta = Current AND NOT
  Previous is empty, forcing the score to 0 regardless of attention. Verified only against
  hand-built synthetic masks before this experiment -- never run on real diffusion output.

This script is the first time metric B runs on real generated images with real captured
attention, replicating Track 1's Real / Shuffled / Substituted design so it can be compared
head-to-head against the 0.83-vs-0.83 persistence result it's meant to fix.

Why this isn't a re-run on the *actual* CR pilot chains
--------------------------------------------------------
The CR pilot's chains (coig/create_images/multi_step_out/) were generated by Gemini
2.5 Flash Image through Google's API -- a closed model. Metric B needs to hook cross-
attention inside the generating UNet (`attn2`), which is impossible against a closed API;
we only have the final pixels, not the model internals. So this experiment builds new,
analogous locked chains with SD1.5 (open, hookable) instead of re-scoring the Gemini
pixels. This is a real fidelity tradeoff, disclosed here and in the writeup: we are
validating the *mechanism* (does Delta-Mask + attention discriminate real from
shuffled/substituted the way persistence-checking couldn't?) on an open substitute model,
not literally re-analyzing CoIG's own Gemini-generated chains. Phase A's Delta-Mask logic
is architecture-agnostic; Phase B's attention hook is UNet-specific either way (see the
DiT-scope note in pilot/spatial_semantic_alignment.py), so SD1.5 is a faithful stand-in
for the mechanism being tested, just not for the exact pixels CoIG itself produces.

How the lock is simulated
--------------------------
Each of the 9 MECHANISM_PROMPTS specs (already validated in metric A: n=2/3/4 subjects,
SD1.5 renders them with Mask R-CNN-detectable people) is decomposed into a chain:
  step 0  = base image, subjects only, no attributes ("a photo of a barista and a cyclist")
  step i  = attribute i inpainted onto subject i's detected bounding box, i = 1..k

The lock is mechanically enforced via a RePaint-style per-step latent blend on the plain
SD1.5 txt2img UNet (see encode_to_latents/mask_to_latent_tensor and the callback in
build_chain): at every denoising step, the region outside the subject's mask is forced to
match the correctly-noised original image at that step's noise level, so by the final step
(noise level 0) that region is exactly the original pixels -- including attributes already
added at earlier steps -- and only the masked region is the model's own new generation.
(A dedicated SD1.5 inpainting checkpoint was tried first; every available community mirror
only ships pickle-format weights, which the pinned torch==2.5.1 -- required for T4/P100
dual-arch support -- cannot load under transformers' torch.load security gate. This
RePaint approach needs no second checkpoint at all.)

Scoring: attention held constant, delta-mask target varied
-------------------------------------------------------------
For attribute i, its cross-attention map A_i is captured once, at its true introduction
step i (the early structural window, steps 0-50% of the denoising schedule). That same
A_i is then paired with three different delta-mask targets:
  REAL         : delta(attr_i, step=i)            -- correct attribute, correct step
  SHUFFLED     : delta(attr_i, step=j != i)        -- correct attribute, wrong step (same chain)
  SUBSTITUTED  : delta(foreign_attr, step=i)        -- an attribute from a *different* chain,
                                                       never rendered anywhere in this chain

Holding attention fixed and only varying the delta-mask target isolates what Phase A's
lock-immunity is actually doing: if the metric's discrimination came from cherry-picked
attention rather than the delta mask correctly gating on true introduction location, this
design would not show it -- the same A_i is used in all three conditions.

A fourth condition, ATTENTION-SCRAMBLED (within the REAL step only), holds the delta mask
fixed at its correct target and swaps in a *different* attribute's attention map instead.
This is metric A's own Tier-1 falsification test #1 (attention-randomization), ported
into the chain setting: if Phase C's score depended only on delta-mask size and not on
attention content, this condition would score the same as REAL. If attention content
genuinely matters, it should drop.

Expected pre-registered result (this is what the CR pilot's persistence check could not
show): REAL scores meaningfully higher than SHUFFLED, SUBSTITUTED, and
ATTENTION-SCRAMBLED, which should all cluster near the metric's structural floor.
"""

